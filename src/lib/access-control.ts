import fs from 'fs';
import path from 'path';
import { getDatabase } from './db';
import { formatTimestamp, getSystemSettings } from './settings';

export interface BlockAdapterSyncResult {
  squidAclPath: string;
  pfsenseAliasPath: string;
  totalBlockedDomains: number;
  syncedAt: number;
}

/**
 * Synchronize blocked domains with Squid ACL and pfSense alias adapter files
 */
export function syncBlockAdapters(): BlockAdapterSyncResult {
  const db = getDatabase();
  const rows = db.prepare(`
    SELECT target
    FROM access_control_rules
    WHERE type = 'block_domain' AND enabled = 1
    ORDER BY target ASC
  `).all() as any[];

  const domains = rows.map((r) => r.target.trim().toLowerCase()).filter(Boolean);

  const dataDir = path.resolve(process.cwd(), 'data');
  if (!fs.existsSync(dataDir)) {
    fs.mkdirSync(dataDir, { recursive: true });
  }

  // 1. Squid ACL format (e.g. .facebook.com)
  const squidAclPath = path.join(dataDir, 'squid_blocked_domains.acl');
  const squidLines = [
    '# ====================================================================',
    '# Squid Proxy Blocked Domains ACL',
    '# Auto-generated by Nippon BPO NOC Access Control Adapter',
    `# Synced at: ${new Date().toISOString()}`,
    '# Usage in squid.conf: acl blocked_domains dstdomain "/path/to/squid_blocked_domains.acl"',
    '# ====================================================================',
    ...domains.map((d) => (d.startsWith('.') ? d : `.${d}`)),
  ];
  fs.writeFileSync(squidAclPath, squidLines.join('\n') + '\n', 'utf8');

  // 2. pfSense Alias Table format (Hostnames/Domains)
  const pfsenseAliasPath = path.join(dataDir, 'pfsense_blocked_hosts.txt');
  const pfsenseLines = [
    '# ====================================================================',
    '# pfSense Firewall Blocked Hosts Table',
    '# Compatible with pfSense Firewall -> Aliases -> URL Table (IPs/Hosts)',
    `# Synced at: ${new Date().toISOString()}`,
    '# ====================================================================',
    ...domains,
  ];
  fs.writeFileSync(pfsenseAliasPath, pfsenseLines.join('\n') + '\n', 'utf8');

  return {
    squidAclPath,
    pfsenseAliasPath,
    totalBlockedDomains: domains.length,
    syncedAt: Date.now(),
  };
}

export interface AccessRule {
  id: number;
  type: 'block_domain' | 'full_access_ip';
  target: string;
  enabled: boolean;
  comment: string | null;
  createdAt: number;
  updatedAt: number;
}

export interface AccessAuditRecord {
  id: number;
  timestamp: number;
  formattedTime: string;
  action: string;
  target: string;
  operator: string;
  reason: string | null;
}

export function getAccessControlRules(): AccessRule[] {
  const db = getDatabase();
  const rows = db.prepare(`
    SELECT id, type, target, enabled, comment, created_at, updated_at
    FROM access_control_rules
    ORDER BY updated_at DESC
  `).all() as any[];

  return rows.map((r) => ({
    id: r.id,
    type: r.type,
    target: r.target,
    enabled: Boolean(r.enabled),
    comment: r.comment,
    createdAt: r.created_at,
    updatedAt: r.updated_at,
  }));
}

export function getAccessControlAuditLog(limit = 50): AccessAuditRecord[] {
  const db = getDatabase();
  const rows = db.prepare(`
    SELECT id, timestamp, action, target, operator, reason
    FROM access_control_audit
    ORDER BY timestamp DESC
    LIMIT ?
  `).all(limit) as any[];

  const tz = getSystemSettings().timezone || 'Asia/Colombo';
  return rows.map((r) => ({
    id: r.id,
    timestamp: r.timestamp,
    formattedTime: formatTimestamp(r.timestamp, tz),
    action: r.action,
    target: r.target,
    operator: r.operator,
    reason: r.reason,
  }));
}

export function blockDomain(domain: string, operator = 'admin', reason = 'Manual block via dashboard'): BlockAdapterSyncResult {
  const db = getDatabase();
  const clean = domain.trim().toLowerCase();
  const now = Date.now();

  db.prepare(`
    INSERT INTO access_control_rules (type, target, enabled, comment, created_at, updated_at)
    VALUES ('block_domain', ?, 1, ?, ?, ?)
    ON CONFLICT(target) DO UPDATE SET
      type = 'block_domain',
      enabled = 1,
      comment = excluded.comment,
      updated_at = excluded.updated_at
  `).run(clean, reason, now, now);

  // Sync to Squid ACL and pfSense alias file adapters
  const sync = syncBlockAdapters();
  const auditReason = `${reason} (Adapter: Synced ${sync.totalBlockedDomains} rules to Squid ACL & pfSense)`;

  db.prepare(`
    INSERT INTO access_control_audit (timestamp, action, target, operator, reason)
    VALUES (?, 'block_domain', ?, ?, ?)
  `).run(now, clean, operator, auditReason);

  return sync;
}

export function unblockDomain(domain: string, operator = 'admin', reason = 'Unblocked via dashboard'): BlockAdapterSyncResult {
  const db = getDatabase();
  const clean = domain.trim().toLowerCase();
  const now = Date.now();

  db.prepare(`
    DELETE FROM access_control_rules
    WHERE type = 'block_domain' AND target = ?
  `).run(clean);

  // Sync to Squid ACL and pfSense alias file adapters
  const sync = syncBlockAdapters();
  const auditReason = `${reason} (Adapter: Synced ${sync.totalBlockedDomains} rules to Squid ACL & pfSense)`;

  db.prepare(`
    INSERT INTO access_control_audit (timestamp, action, target, operator, reason)
    VALUES (?, 'unblock_domain', ?, ?, ?)
  `).run(now, clean, operator, auditReason);

  return sync;
}

